"""Discover Markdown notes and generate classified, accessible static reading pages."""
from collections import Counter
from dataclasses import dataclass, field
from datetime import date, datetime
from html import escape
import json
import os
from pathlib import Path
import re
import subprocess
from urllib.parse import quote, unquote, urlsplit, urlunsplit

import yaml
from markdown_it import MarkdownIt
from mdit_py_plugins.dollarmath import dollarmath_plugin
from mdit_py_plugins.footnote import footnote_plugin
from mdit_py_plugins.tasklists import tasklists_plugin
from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import get_lexer_by_name
from pygments.util import ClassNotFound

MARKER = "<!-- Generated by scripts/notes.py; edit the Markdown source. -->"
NOTE_HEAD = '<link rel="stylesheet" href="{root}/assets/css/notes.css">'
ARTICLE_HEAD = NOTE_HEAD + '\n<link rel="stylesheet" href="{root}/assets/vendor/katex/katex.min.css">\n<link rel="stylesheet" href="{root}/assets/css/code.css">'


def esc(value):
    return escape(str(value), quote=True)


def slug(text):
    return re.sub(r"[^\w\-]+", "-", text.casefold()).strip("-") or "section"


def relative_url(target, directory):
    return quote(Path(os.path.relpath(target, directory)).as_posix(), safe="/-._~")


def output_for(source, source_root, output_root):
    target = output_root / source.relative_to(source_root)
    if source.stem.lower() in ("main", "index") and source.parent != source_root:
        return target.with_name("index.html")
    return target.with_name("index-note.html") if source.stem.lower() == "index" else target.with_suffix(".html")


def split_frontmatter(text):
    text = text.lstrip("\ufeff").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        return {}, text
    match = re.match(r"\A---\n(.*?)\n(?:---|\.\.\.)\s*(?:\n|$)", text, re.S)
    if not match:
        raise ValueError("YAML metadata is missing its closing --- line")
    meta = yaml.safe_load(match.group(1)) or {}
    if not isinstance(meta, dict):
        raise ValueError("YAML metadata must be a mapping")
    return meta, text[match.end():]


def date_value(value):
    if value is None:
        return ""
    if isinstance(value, (date, datetime)):
        return value.isoformat()[:10]
    # Accept the example's single-digit hour, without depending on local timezones.
    match = re.match(r"^(\d{4}-\d{2}-\d{2})(?:[ T].*)?$", str(value))
    if not match:
        raise ValueError(f"Use a YYYY-MM-DD date: {value!r}")
    return date.fromisoformat(match.group(1)).isoformat()


def inline_text(tokens):
    return "".join(t.content if t.type in ("text", "code_inline", "math_inline", "math_inline_double") else " " if t.type in ("softbreak", "hardbreak") else "" for t in tokens)


def highlight_code(code, language, _attributes):
    try:
        lexer = get_lexer_by_name(language.strip().split()[0])
    except (ClassNotFound, IndexError):
        return f'<pre class="codehilite"><code>{esc(code)}</code></pre>'
    return highlight(code, lexer, HtmlFormatter(cssclass="codehilite"))


@dataclass
class Note:
    source: Path
    output: Path
    meta: dict
    body: str
    category: str
    title: str
    published: str
    cover: str = ""
    summary: str = ""
    preview_summary: str = ""
    search: str = ""
    headings: list = field(default_factory=list)
    html: str = ""


class NoteLibrary:
    def __init__(self, base):
        self.base = Path(base).resolve()
        self.root = self.base / "note"
        self.source_root = self.base / "files/notes"
        self.notes = []
        self.equations = []
        self.paths = {}
        self.categories = {}
        config = self.base / "content/note-categories.json"
        if config.exists():
            self.categories = json.loads(config.read_text(encoding="utf-8"))

    def discover(self):
        outputs = set()
        for source in sorted(self.source_root.rglob("*.md")):
            if any(p.startswith(".") for p in source.relative_to(self.source_root).parts):
                continue
            meta, body = split_frontmatter(source.read_text(encoding="utf-8-sig"))
            if meta.get("draft") is True:
                continue
            output = output_for(source, self.source_root, self.root)
            if str(output).casefold() in outputs:
                raise ValueError(f"Two notes would overwrite the same page: {output}")
            if output.exists() and MARKER not in output.read_text(encoding="utf-8"):
                raise ValueError(f"Refusing to overwrite a handwritten page: {output}")
            outputs.add(str(output).casefold())
            folders = source.relative_to(self.source_root).parts[:-1]
            category = str(meta.get("category") or (folders[0] if folders else "未分类"))
            heading = re.search(r"^#\s+(.+)$", body, re.M)
            title = str(meta.get("title") or (heading.group(1) if heading else source.parent.name if source.stem.lower() in ("main", "index") else source.stem))
            note = Note(source, output, meta, body, category, title, date_value(meta.get("date")))
            self.notes.append(note)
            self.paths[source.resolve()] = output
        self.notes.sort(key=lambda n: (n.published, n.title.casefold()), reverse=True)
        return self.notes

    def category_label(self, category):
        return self.categories.get(category, {}).get("label", category)

    def ordered_categories(self):
        return sorted(
            {note.category for note in self.notes},
            key=lambda category: (category.casefold() == "others" or self.category_label(category) == "杂记", category.casefold()),
        )

    def resolve_link(self, raw, note):
        parts = urlsplit(raw)
        if parts.scheme or parts.netloc:
            if parts.scheme.lower() not in ("http", "https", "mailto", "tel"):
                raise ValueError(f"Unsupported link in {note.source}: {raw}")
            return raw
        if not parts.path:
            return raw
        path = unquote(parts.path)
        target = (self.base / path.lstrip("/") if path.startswith("/") else note.source.parent / path).resolve()
        if not target.is_relative_to(self.base):
            raise ValueError(f"Link points outside the site: {raw}")
        if target.suffix.lower() == ".md":
            if target not in self.paths:
                raise ValueError(f"Linked Markdown note is missing or a draft: {raw}")
            target = self.paths[target]
        elif not target.exists():
            raise ValueError(f"Missing local asset in {note.source}: {raw}")
        return urlunsplit(("", "", relative_url(target, note.output.parent), parts.query, parts.fragment))

    def math_placeholder(self, tex, options):
        index = len(self.equations)
        self.equations.append({"tex": tex, "display": options.get("display_mode", False)})
        return f"<!--fft-equation-{index}-->"

    def parse(self, note):
        md = MarkdownIt("commonmark", {"html": False, "highlight": highlight_code})
        md.enable(["table", "strikethrough"])
        md.use(footnote_plugin).use(tasklists_plugin, label=True)
        md.use(dollarmath_plugin, double_inline=True, renderer=self.math_placeholder)
        def display_math(renderer, items, index, options, env):
            token = items[index]
            tag = "span" if token.type == "math_inline_double" else "div"
            identifier = f' id="{esc(token.info)}"' if token.info else ""
            equation = self.math_placeholder(token.content.strip(), {"display_mode": True})
            return f'<{tag} class="math block"{identifier} tabindex="0" role="region" aria-label="数学公式，可横向滚动">{equation}</{tag}>'
        for token_type in ("math_block", "math_block_label", "math_inline_double"):
            md.add_render_rule(token_type, display_math)
        env = {}
        tokens = md.parse(note.body, env)
        paragraphs = []
        all_text = []
        used_ids = Counter()
        image_number = 0
        for i, token in enumerate(tokens):
            if token.type == "heading_open":
                text = inline_text(tokens[i + 1].children or [])
                identifier = slug(text)
                used_ids[identifier] += 1
                if used_ids[identifier] > 1:
                    identifier += f"-{used_ids[identifier]}"
                token.attrSet("id", identifier)
                level = int(token.tag[1])
                if level == 1:
                    if text.strip() == note.title.strip():
                        token.hidden = tokens[i + 2].hidden = True
                        tokens[i + 1].children = []
                        continue
                    token.tag = tokens[i + 2].tag = "h2"
                    level = 2
                if level <= 4:
                    note.headings.append((level, identifier, text))
            if token.type == "table_open":
                token.attrSet("class", "note-table")
            if token.type != "inline":
                continue
            text = inline_text(token.children or [])
            all_text.append(text)
            if i and tokens[i - 1].type == "paragraph_open" and len(text) >= 35 and not re.match(r"^\s*(?:\[\d+\]|参考(?:教材|文献))", text):
                paragraphs.append(text)
            for child in token.children or []:
                if child.type == "image":
                    image_number += 1
                    child.attrSet("src", self.resolve_link(child.attrGet("src"), note))
                    child.attrSet("loading", "lazy")
                    child.attrSet("decoding", "async")
                    if not child.content.strip():
                        child.content = f"{note.title} · 图 {image_number}"
                        child.children = []
                        child.attrSet("alt", child.content)
                if child.type == "link_open":
                    child.attrSet("href", self.resolve_link(child.attrGet("href"), note))
        # The image renderer normally reconstructs alt text from child tokens.
        def render_image(renderer, items, index, options, env):
            token = items[index]
            if token.children:
                token.attrSet("alt", renderer.renderInlineAsText(token.children, options, env))
            return renderer.renderToken(items, index, options, env)
        md.add_render_rule("image", render_image)
        note.html = md.renderer.render(tokens, md.options, env)
        note.html = note.html.replace('<table class="note-table">', '<div class="table-scroll" tabindex="0" role="region" aria-label="表格，可横向滚动"><table class="note-table">').replace("</table>", "</table></div>")
        note.preview_summary = str(note.meta.get("summary") or "").strip()
        note.search = " ".join([note.title, note.category, self.category_label(note.category), note.preview_summary, *all_text])
        summary = str(note.preview_summary or note.meta.get("description") or (paragraphs[0] if paragraphs else ""))
        note.summary = summary[:125].rstrip() + ("…" if len(summary) > 125 else "")
        if note.meta.get("cover"):
            note.cover = self.resolve_link(str(note.meta["cover"]), note)

    def render_math(self):
        if not self.equations:
            return
        process = subprocess.run(
            ["node", str(self.base / "scripts/render-math.cjs")],
            input=json.dumps(self.equations, ensure_ascii=False), capture_output=True,
            text=True, encoding="utf-8", check=True,
        )
        results = json.loads(process.stdout)
        replacements = {}
        for index, result in enumerate(results):
            if "error" in result:
                raise ValueError(f"Equation {index + 1}: {result['error']}\n{self.equations[index]['tex']}")
            replacements[str(index)] = result["html"]
        for note in self.notes:
            note.html = re.sub(r"<!--fft-equation-(\d+)-->", lambda match: replacements[match.group(1)], note.html)

    def card(self, note):
        href = relative_url(note.output, self.root)
        cover = ""
        if note.cover:
            # The stored URL is relative to the article; resolve it for the directory.
            parts = urlsplit(note.cover)
            src = note.cover if parts.scheme else relative_url((note.output.parent / unquote(parts.path)).resolve(), self.root)
            cover = f'<img class="note-card-cover" src="{esc(src)}" alt="" loading="lazy">'
        published = f'<time datetime="{note.published}">{note.published.replace("-", ".")}</time>' if note.published else "未标注日期"
        summary = f'<p class="note-card-summary">{esc(note.preview_summary)}</p>' if note.preview_summary else ""
        return f'''<article class="note-card" data-note data-category="{esc(note.category)}" data-search="{esc(note.search)}">
          <a class="note-card-link" href="{href}">{cover}<div class="note-card-body">
          <p class="note-meta">{published}</p><h3>{esc(note.title)}</h3>{summary}
          <span class="note-read">阅读全文 <span aria-hidden="true">↗</span></span></div></a></article>'''

    def directory(self):
        counts = Counter(n.category for n in self.notes)
        categories = self.ordered_categories()
        links = f'<a href="#notes" data-category-filter="" aria-current="true">全部笔记 <span>{len(self.notes):02d}</span></a>'
        groups = ""
        for index, category in enumerate(categories):
            identifier = f"category-{index + 1}"
            label = self.category_label(category)
            links += f'<a href="#{identifier}" data-category-filter="{esc(category)}">{esc(label)} <span>{counts[category]:02d}</span></a>'
            eyebrow = f'<p class="eyebrow">{esc(category)}</p>' if label != category else ""
            cards = "".join(self.card(n) for n in self.notes if n.category == category)
            groups += f'''<section class="note-group" id="{identifier}" data-note-group><header class="note-group-heading"><div>{eyebrow}<h2 id="{identifier}-heading" tabindex="-1">{esc(label)} <span>{counts[category]:02d}</span></h2></div><a class="note-more" href="#{identifier}" data-category-filter="{esc(category)}" aria-label="更多{esc(label)}笔记">更多 <span aria-hidden="true">→</span></a></header><div class="note-grid" role="region" aria-labelledby="{identifier}-heading" tabindex="0">{cards}</div></section>'''
        if not self.notes:
            groups = '<div class="empty-state"><h2>下一页，留给新的思考。</h2><p>笔记正在整理中。</p></div>'
        return f'''{MARKER}<header class="page-heading"><p class="eyebrow">学习笔记</p><h1>Note<span class="title-period">.</span></h1></header>
          <div class="notes-layout notes-overview" id="notes"><aside class="note-sidebar"><p class="eyebrow">按主题阅读</p><nav class="note-categories" aria-label="笔记分类">{links}</nav><p class="note-library-count">{len(categories):02d} 个主题 · {len(self.notes):02d} 篇笔记</p></aside>
          <div class="note-list"><div class="note-search" hidden><label for="note-search">搜索笔记</label><div class="note-search-field"><input id="note-search" type="search" placeholder="标题、关键词或正文…" autocomplete="off"><button type="button" id="clear-note-search" aria-label="清空搜索">清空</button></div><p id="note-results" role="status" aria-live="polite">共 {len(self.notes)} 篇笔记</p></div>
          {groups}<div class="note-no-results" hidden><h2>还没有找到这篇笔记</h2><p>试试其他关键词，或切换到全部笔记。</p></div></div></div>'''

    def article(self, note):
        directory = relative_url(self.root / "index.html", note.output.parent)
        category_index = self.ordered_categories().index(note.category) + 1
        category_url = f"{directory}#category-{category_index}"
        category = esc(self.category_label(note.category))
        toc = "".join(f'<li class="toc-level-{level}"><a href="#{quote(identifier)}">{esc(text)}</a></li>' for level, identifier, text in note.headings)
        published = f'<time datetime="{note.published}">{note.published.replace("-", ".")}</time>' if note.published else "未标注日期"
        cover = f'<img class="article-cover" src="{esc(note.cover)}" alt="" fetchpriority="high">' if note.cover else ""
        source = relative_url(note.source, note.output.parent)
        category_notes = [n for n in self.notes if n.category == note.category]
        next_note = category_notes[(category_notes.index(note) + 1) % len(category_notes)]
        related_link = f'<a href="{relative_url(next_note.output, note.output.parent)}">{esc(next_note.title)} <span aria-hidden="true">↗</span></a>'
        related_html = f'<section class="related-notes"><h2>继续阅读 · {category}</h2>{related_link}</section>' if len(category_notes) > 1 else ""
        return f'''{MARKER}<nav class="note-breadcrumbs" aria-label="当前位置"><a href="{directory}">Note</a><span aria-hidden="true">/</span><a href="{category_url}">{category}</a></nav>
          <header class="article-heading"><div><p class="eyebrow">{esc(note.category)}</p><h1>{esc(note.title)}</h1><p class="note-meta">{published}<a href="{source}" download>下载 Markdown <span aria-hidden="true">↓</span></a></p></div>{cover}</header>
          <div class="reading-layout"><aside class="article-sidebar"><details class="note-toc" open><summary>本篇目录</summary><nav aria-label="文章目录"><ol>{toc}</ol></nav></details><a class="back-to-notes" href="{directory}">← 全部笔记</a></aside>
          <div class="article-content"><article class="markdown-body" aria-label="笔记正文">{note.html}</article>{related_html}<div class="page-end"><a href="{directory}">← 返回笔记目录</a><a href="#main">回到顶部 ↑</a></div></div></div>'''

    def remove_stale(self):
        manifest = self.root / ".generated-pages.json"
        current = [n.output.relative_to(self.root).as_posix() for n in self.notes]
        previous = json.loads(manifest.read_text(encoding="utf-8")) if manifest.exists() else []
        for path in set(previous) - set(current):
            target = (self.root / path).resolve()
            if not target.is_relative_to(self.root.resolve()) or target.suffix != ".html" or target == self.root / "index.html":
                raise ValueError(f"Invalid generated-page path: {path}")
            if target.exists() and MARKER in target.read_text(encoding="utf-8"):
                target.unlink()
        manifest.write_text(json.dumps(current, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def build_notes(base, render):
    library = NoteLibrary(base)
    library.discover()
    for note in library.notes:
        library.parse(note)
    library.render_math()
    for note in library.notes:
        render("note", library.article(note), note.summary or note.title, note.title + " | Flowers for Tuesday", output=note.output.relative_to(base).as_posix(), extra_head=ARTICLE_HEAD)
    render("note", library.directory(), "按主题分类的学习笔记、理论推导与计算方法。", "Note | Flowers for Tuesday", extra_head=NOTE_HEAD + '\n<script src="{root}/assets/js/notes.js" defer></script>')
    (base / "assets/css/code.css").write_text(HtmlFormatter(style="friendly").get_style_defs(".codehilite") + "\n", encoding="utf-8")
    library.remove_stale()
    print(f"Built {len(library.notes)} Markdown notes and {len(library.equations)} equations.")
