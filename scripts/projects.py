"""Build research projects from a metadata file, log.md and standard Markdown notes."""
from dataclasses import dataclass, field
import json
from pathlib import Path
import re

from notes import ARTICLE_HEAD, Note, NoteLibrary, date_value, esc, relative_url, split_frontmatter
from references import Reference, citation_plugin, read_references

MARKER = "<!-- Generated by scripts/projects.py; edit files/research or files/projects. -->"
PROJECT_HEAD = ARTICLE_HEAD + '\n<link rel="stylesheet" href="{root}/assets/css/projects.css">'
SOURCE_ROOTS = ("files/research", "files/projects")
RESEARCH_NOTE_CATEGORY = "Research Notes"
PROJECT_STATUSES = {
    "draft": "Draft",
    "review": "Review",
    "published": "Published",
}


def note_timestamp(note):
    """Retain optional hours/minutes while matching the existing Note date syntax."""
    value = str(note.meta.get("date") or "")
    match = re.fullmatch(r"\d{4}-\d{2}-\d{2}[ T](\d{1,2}):(\d{2})(?::(\d{2}))?", value)
    if match:
        hour, minute, second = (int(part or 0) for part in match.groups())
        if hour > 23 or minute > 59 or second > 59:
            raise ValueError(f"Invalid note time in {note.source}: {value}")
        return f"{note.published}T{hour:02d}:{minute:02d}:{second:02d}"
    return note.published


@dataclass
class Project:
    source: Path
    output: Path
    meta: dict
    title: str
    library: NoteLibrary
    log: Note | None = None
    cover: str = ""
    references: list[Reference] = field(default_factory=list)


class ProjectLibrary:
    def __init__(self, base):
        self.base = Path(base).resolve()
        self.root = self.base / "research"
        self.projects = []
        self.renderer = NoteLibrary(self.base)

    def discover(self):
        # Resolve links to the existing Note collection as well as other projects.
        self.renderer.discover()
        self.renderer.notes = []
        names = set()
        for folder in SOURCE_ROOTS:
            source_root = self.base / folder
            if not source_root.exists():
                continue
            for source in sorted(source_root.iterdir()):
                if not source.is_dir() or source.name.startswith("."):
                    continue
                metadata = source / "project.json"
                meta = json.loads(metadata.read_text(encoding="utf-8-sig")) if metadata.exists() else {}
                if not isinstance(meta, dict):
                    raise ValueError(f"Project metadata must be an object: {metadata}")
                if meta.get("draft") is True:
                    continue
                if source.name.casefold() in names:
                    raise ValueError(f"Duplicate project folder name: {source.name}")
                names.add(source.name.casefold())
                output = self.root / source.name / "index.html"
                title = str(meta.get("title") or source.name)
                library = NoteLibrary(self.base)
                library.source_root = source / "notes"
                library.root = output.parent / "notes"
                library.discover()
                for note in library.notes:
                    note.category = RESEARCH_NOTE_CATEGORY
                    note.meta["category"] = RESEARCH_NOTE_CATEGORY
                library.notes.sort(key=lambda n: (note_timestamp(n), n.title.casefold()), reverse=True)
                project = Project(source, output, meta, title, library)
                project.references = read_references(source / "assets/references.bib")
                log_path = source / "log.md"
                if log_path.exists():
                    log_meta, body = split_frontmatter(log_path.read_text(encoding="utf-8-sig"))
                    if body.strip() and log_meta.get("draft") is not True:
                        project.log = Note(log_path, output, log_meta, body, title, str(log_meta.get("title") or "研究日志"), "")
                        self.renderer.paths[log_path.resolve()] = output
                        self.renderer.notes.append(project.log)
                self.renderer.paths.update(library.paths)
                self.renderer.notes.extend(library.notes)
                self.projects.append(project)
        self.projects.sort(key=lambda p: (date_value(p.meta.get("date")), p.title.casefold()), reverse=True)
        return self.projects

    def parse(self):
        for project in self.projects:
            notes = ([project.log] if project.log else []) + project.library.notes
            for note in notes:
                note.references = project.references
                self.renderer.parse(note, configure=lambda md: md.use(
                    citation_plugin, project.references, "", note.source))
        self.renderer.render_math()
        for project in self.projects:
            cover = str(project.meta.get("cover") or "").strip()
            if cover:
                context = Note(project.source / "project.json", project.output, {}, "", "", "", "")
                project.cover = self.renderer.resolve_link(cover, context)
                for note in project.library.notes:
                    if not note.cover:
                        context.output = note.output
                        note.cover = self.renderer.resolve_link(cover, context)

    def links(self, project):
        links = project.meta.get("links")
        if links is None:
            links = {}
        if not isinstance(links, dict):
            raise ValueError(f"Project links must be a label-to-URL object: {project.source / 'project.json'}")
        output = []
        context = Note(project.source / "project.json", project.output, {}, "", "", "", "")
        for label, value in links.items():
            if value is None:
                continue
            if not isinstance(value, str):
                raise ValueError(f"Project link {label!r} must be a URL string: {project.source / 'project.json'}")
            value = value.strip()
            if not value:
                continue
            if "\\" in value or any(ord(c) < 32 for c in value):
                raise ValueError(f"Invalid project URL: {value!r}")
            url = self.renderer.resolve_link(value, context)
            output.append(f'<a class="text-link" href="{esc(url)}">{esc(label)} <span aria-hidden="true">↗</span></a>')
        return f'<nav class="project-links" aria-label="论文与相关资源">{"".join(output)}</nav>' if output else ""

    def facts(self, project):
        items = []
        if project.meta.get("status"):
            status = str(project.meta["status"]).strip().lower()
            if status not in PROJECT_STATUSES:
                raise ValueError(f"Project status must be draft, review or published: {project.source / 'project.json'}")
            items.append(f'<span class="project-status project-status--{status}" lang="en">{PROJECT_STATUSES[status]}</span>')
        if project.meta.get("date"):
            value = date_value(project.meta["date"])
            items.append(f'<time datetime="{value}">{value.replace("-", ".")}</time>')
        return f'<p class="project-meta">{"".join(items)}</p>' if items else ""

    def directory(self):
        cards = []
        for project in self.projects:
            cover = ""
            if project.cover:
                context = Note(project.source / "project.json", self.root / "index.html", {}, "", "", "", "")
                src = self.renderer.resolve_link(str(project.meta["cover"]), context)
                cover = f'<img class="project-card-cover" src="{esc(src)}" alt="" loading="lazy">'
            description = f'<p class="project-description">{esc(project.meta["description"])}</p>' if project.meta.get("description") else ""
            cards.append(f'''<article class="project-card"><a class="project-card-link" href="{relative_url(project.output, self.root)}">
              {cover}<div class="project-card-copy">{self.facts(project)}<h2>{esc(project.title)}</h2>{description}
              <span class="project-card-end"><span>{len(project.library.notes):02d} 篇研究笔记</span><span>进入课题 ↗</span></span></div></a></article>''')
        content = "".join(cards) or '<div class="empty-state"><h2>每一份探索，都值得记录。</h2><p>研究课题正在整理中。</p></div>'
        return f'''{MARKER}<header class="page-heading"><p class="eyebrow">研究课题</p><h1>Research<span class="title-period">.</span></h1></header>
          <section class="project-directory" aria-label="研究课题"><div class="collection-heading"><h2>Research Projects</h2><span>{len(self.projects):02d} 个课题</span></div>{content}</section>'''

    def page(self, project):
        directory = relative_url(self.root / "index.html", project.output.parent)
        cover = f'<img class="project-cover" src="{esc(project.cover)}" alt="" fetchpriority="high">' if project.cover else ""
        description = f'<p class="project-description">{esc(project.meta["description"])}</p>' if project.meta.get("description") else ""
        details = "".join(f'<p class="project-detail">{esc(project.meta[key])}</p>' for key in ("authors", "venue") if project.meta.get(key))
        sections, navigation = [], []
        if project.log:
            navigation.append('<a href="#research-log">研究日志 <span>01</span></a>')
            sections.append(f'<section class="project-section" id="research-log"><header class="project-section-heading"><p class="eyebrow">Research Log</p><h2>研究日志</h2></header><div class="markdown-body">{project.log.html}</div></section>')
        if project.library.notes:
            navigation.append(f'<a href="#research-notes">课题笔记 <span>{len(project.library.notes):02d}</span></a>')
            rows = []
            for note in project.library.notes:
                timestamp = note_timestamp(note)
                clock = f'<span class="project-note-clock">{timestamp[11:16]}</span>' if "T" in timestamp else ""
                published = f'<time datetime="{timestamp}">{note.published.replace("-", ".")}{clock}</time>' if note.published else '<span>未标注日期</span>'
                summary = f'<p class="project-note-summary">{esc(note.preview_summary)}</p>' if note.preview_summary else ""
                cover_src = project.cover
                if note.meta.get("cover"):
                    context = Note(note.source, project.output, {}, "", "", "", "")
                    cover_src = self.renderer.resolve_link(str(note.meta["cover"]), context)
                note_cover = f'<img class="project-note-cover" src="{esc(cover_src)}" alt="" loading="lazy" decoding="async">' if cover_src else ""
                rows.append(f'<li class="project-note-row" data-category="{RESEARCH_NOTE_CATEGORY}"><div class="project-note-date">{published}</div><a class="project-note-link" href="{relative_url(note.output, project.output.parent)}">{note_cover}<div class="project-note-copy"><h3>{esc(note.title)}</h3>{summary}<span class="project-note-read">阅读全文 ↗</span></div></a></li>')
            sections.append(f'<section class="project-section" id="research-notes"><header class="project-section-heading"><p class="eyebrow">Research Notes</p><h2>课题笔记 <span>{len(rows):02d}</span></h2></header><ol class="project-note-list">{"".join(rows)}</ol></section>')
        if project.references:
            count = len(project.references)
            navigation.append(f'<a href="#research-references">参考文献 <span>{count:02d}</span></a>')
            citations = "".join(reference.html(index) for index, reference in enumerate(project.references, 1))
            sections.append(f'<section class="project-section" id="research-references"><header class="project-section-heading"><p class="eyebrow">References</p><h2>参考文献 <span>{count:02d}</span></h2></header><ol class="reference-list">{citations}</ol></section>')
        body = f'<div class="project-layout"><aside class="project-sidebar"><p class="eyebrow">PROJECT INDEX</p><nav aria-label="课题目录">{"".join(navigation)}</nav></aside><div class="project-content">{"".join(sections)}</div></div>' if sections else ""
        return f'''{MARKER}<nav class="note-breadcrumbs" aria-label="当前位置"><a href="{directory}">Research</a><span aria-hidden="true">/</span><span>{esc(project.title)}</span></nav>
          <header class="project-heading"><div class="project-heading-copy"><p class="eyebrow">Research Project</p><h1>{esc(project.title)}</h1>{self.facts(project)}{description}{details}{self.links(project)}</div>{cover}</header>
          {body}<div class="page-end"><a href="{directory}">← 全部课题</a><a href="#main">回到顶部 ↑</a></div>'''

    def build(self, render):
        self.discover()
        self.parse()
        pages = {}
        for project in self.projects:
            pages[project.output] = (self.page(project), str(project.meta.get("description") or project.title), project.title)
            for note in project.library.notes:
                article = project.library.article(note, directory_path=project.output, collection_label="Research", return_label="课题主页", category_anchor="research-notes", breadcrumb_label=project.title)
                pages[note.output] = (MARKER + article, note.summary or note.title, note.title)
        for target in pages:
            if target.exists() and MARKER not in target.read_text(encoding="utf-8"):
                raise ValueError(f"Refusing to overwrite a handwritten page: {target}")
        for target, (html, description, title) in pages.items():
            render("research", html, description, title + " | Flowers for Tuesday", output=target.relative_to(self.base).as_posix(), extra_head=PROJECT_HEAD)
        render("research", self.directory(), "研究课题、研究日志与论文成果。", "Research | Flowers for Tuesday", extra_head=PROJECT_HEAD)
        self.root.mkdir(parents=True, exist_ok=True)
        manifest = self.root / ".generated-projects.json"
        previous = json.loads(manifest.read_text(encoding="utf-8")) if manifest.exists() else []
        current = [path.relative_to(self.root).as_posix() for path in pages]
        for path in set(previous) - set(current):
            target = (self.root / path).resolve()
            if target.is_relative_to(self.root.resolve()) and target.is_file() and target.suffix == ".html" and MARKER in target.read_text(encoding="utf-8"):
                target.unlink()
        manifest.write_text(json.dumps(current, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Built {len(self.projects)} research projects and {sum(len(p.library.notes) for p in self.projects)} project notes.")


def build_projects(base, render):
    ProjectLibrary(base).build(render)
