"""Build photo journals and a coordinate-driven, progressively enhanced gallery."""
from dataclasses import dataclass, field
from datetime import date
import json
import math
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

from notes import Note, NoteLibrary, esc, relative_url, split_frontmatter

MARKER = "<!-- Generated by scripts/gallery.py; edit files/gallery instead. -->"
HEAD = '''<link rel="stylesheet" href="{root}/assets/css/gallery.css">
<script src="{root}/assets/js/gallery-carousel.js" defer></script>'''
MAP_HEAD = '''<link rel="stylesheet" href="{root}/assets/vendor/leaflet/leaflet.css">
<script src="{root}/assets/vendor/leaflet/leaflet.js" defer></script>
<script src="{root}/assets/js/gallery.js" defer></script>'''


@dataclass
class Journal:
    note: Note
    slug: str
    place: dict
    images: list = field(default_factory=list)


class GalleryLibrary(NoteLibrary):
    def __init__(self, base):
        super().__init__(base)
        self.root = self.base / "gallery"
        self.source_root = self.base / "files/gallery"
        self.journals = []
        self.country_names = {"CN": "中国", "JP": "日本"}
        geography = self.base / "assets/maps/world.geojson"
        if geography.exists():
            for feature in json.loads(geography.read_text(encoding="utf-8"))["features"]:
                properties = feature["properties"]
                code = properties.get("ISO_A2_EH") or properties.get("ISO_A2")
                if code and len(code) == 2:
                    self.country_names.setdefault(code, properties.get("NAME_ZH") or properties.get("ADMIN") or code)

    def discover(self):
        for source in sorted(self.source_root.glob("*/main.md")):
            if source.parent.name.startswith("."):
                continue
            meta, body = split_frontmatter(source.read_text(encoding="utf-8"))
            try:
                if set(meta) - {"title", "date", "place"}:
                    raise ValueError("Gallery metadata only supports title, date and place; images are read from the folder")
                title = meta.get("title")
                if not isinstance(title, str) or not title.strip():
                    raise ValueError("title is required")
                published = str(meta.get("date", ""))
                if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", published):
                    raise ValueError("date must be YYYY-MM-DD")
                date.fromisoformat(published)
                place = meta.get("place")
                if not isinstance(place, dict):
                    raise ValueError("place requires name, country, lat and lng")
                place = dict(place)
                for key, limit in (("lat", 90), ("lng", 180)):
                    value = place.get(key)
                    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or abs(value) > limit:
                        raise ValueError(f"place.{key} must be a finite number in [-{limit}, {limit}]")
                if not isinstance(place.get("name"), str) or not place["name"].strip():
                    raise ValueError("place.name is required")
                if not re.fullmatch(r"[A-Z]{2}", str(place.get("country", ""))):
                    raise ValueError("place.country requires a two-letter country code, e.g. CN or JP")
                slug = source.parent.name
                if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]*", slug):
                    raise ValueError("Use a folder name with ASCII letters, numbers and hyphens")
                output = self.root / slug / "index.html"
                if output.exists() and MARKER not in output.read_text(encoding="utf-8"):
                    raise ValueError(f"Refusing to overwrite handwritten page: {output}")
                note = Note(source, output, meta, body, "Gallery", title.strip(), published)
                self.notes.append(note)
                self.paths[source.resolve()] = output
                self.journals.append(Journal(note, slug, place))
            except ValueError as error:
                raise ValueError(f"{source.relative_to(self.base)}: {error}") from error
        self.journals.sort(key=lambda j: (j.note.published, j.slug), reverse=True)
        for journal in self.journals:
            self.parse(journal.note)
            folder = journal.note.source.parent / "images"
            if not folder.is_dir():
                folder = journal.note.source.parent
            def image_order(path):
                return ([int(part) if part.isdigit() else part.casefold() for part in re.split(r"(\d+)", path.name)], path.name)
            photos = sorted((path for path in folder.iterdir() if path.is_file() and not path.name.startswith(".")
                             and path.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif", ".svg"}), key=image_order)
            if not photos:
                raise ValueError(f"{journal.note.source}: add at least one image to {folder}")
            journal.images = [{"src": self.resolve_link(relative_url(photo, journal.note.source.parent), journal.note),
                               "alt": f"{journal.note.title} · 图 {i}"} for i, photo in enumerate(photos, 1)]
        self.render_math()
        return self.journals

    def photo_url(self, journal, photo):
        src = photo["src"]
        return src if urlsplit(src).scheme else relative_url((journal.note.output.parent / unquote(src)).resolve(), self.root)

    def card(self, journal):
        note = journal.note
        image = journal.images[0]
        return f'''<article class="journal-card" data-journal="{journal.slug}">
          <a class="journal-link" href="{relative_url(note.output, self.root)}" data-open-journal="{journal.slug}">
            <div class="journal-cover"><img src="{esc(self.photo_url(journal, image))}" alt="{esc(image['alt'])}" loading="lazy" decoding="async">
              <span class="photo-count" aria-label="{len(journal.images)} 张图片">▧ {len(journal.images):02d}</span></div>
            <div class="journal-copy"><p class="journal-date"><time datetime="{note.published}">{note.published.replace('-', '.')}</time><span>↗</span></p>
              <h2>{esc(note.title)}</h2><p class="journal-summary">{esc(note.summary)}</p>
              <p class="journal-place"><span aria-hidden="true">⌖</span> {esc(journal.place['name'])}</p></div>
          </a></article>'''

    def entry(self, journal):
        note = journal.note
        photos = "".join(f'''<figure><a href="{esc(photo['src'])}" target="_blank" rel="noopener" aria-label="查看原图：{esc(photo['alt'])}"><img src="{esc(photo['src'])}" alt="{esc(photo['alt'])}" loading="{'eager' if i == 0 else 'lazy'}" decoding="async"></a><figcaption>{esc(photo['alt'])}</figcaption></figure>'''
                         for i, photo in enumerate(journal.images))
        place = journal.place
        return f'''<article class="gallery-entry" aria-labelledby="entry-title">
          <section class="entry-photos" data-carousel aria-label="笔记相册" aria-roledescription="轮播图">
            <div class="carousel-stage"><div class="carousel-viewport" tabindex="0" aria-label="图片，可左右滑动或使用方向键切换">{photos}</div>
              <span class="carousel-counter" role="status" aria-live="polite" aria-atomic="true" hidden></span>
              <button type="button" class="carousel-prev" aria-label="上一张图片" hidden>‹</button>
              <button type="button" class="carousel-next" aria-label="下一张图片" hidden>›</button>
            </div><div class="carousel-dots" role="group" aria-label="选择图片" hidden></div>
          </section>
          <div class="entry-copy"><header><h1 id="entry-title">{esc(note.title)}</h1>
            <p class="journal-date"><time datetime="{note.published}">{note.published.replace('-', '.')}</time> · {esc(place['name'])}</p>
            <p class="entry-coordinates">{place['lat']:.4f}°, {place['lng']:.4f}°</p></header>
            <div class="markdown-body">{note.html}</div>
            <div class="entry-links"><a href="../index.html?place={journal.slug}#footprints">在足迹地图中查看 ↗</a><a href="{relative_url(note.source, note.output.parent)}">Markdown 源文件 ↓</a></div>
          </div></article>'''

    def directory(self):
        data = [{"id": j.slug, "title": j.note.title, "date": j.note.published, "place": j.place,
                 "search": j.note.search + " " + j.place["name"] + " " + self.country_names.get(j.place["country"], j.place["country"]),
                 "url": relative_url(j.note.output, self.root), "count": len(j.images)} for j in self.journals]
        payload = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c").replace("&", "\\u0026")
        countries = len({j.place["country"] for j in self.journals})
        photos = sum(len(j.images) for j in self.journals)
        years = sorted({j.note.published[:4] for j in self.journals}, reverse=True)
        options = "".join(f'<option value="{year}">{year}</option>' for year in years)
        country_codes = sorted({j.place["country"] for j in self.journals})
        country_tabs = ''.join(f'<button type="button" data-scope="{code}" aria-pressed="false">{esc(self.country_names.get(code, code))}</button>' for code in country_codes)
        return f'''{MARKER}
          <header class="page-heading gallery-heading"><p class="eyebrow">旅行碎片</p><h1>Gallery<span class="title-period">.</span></h1></header>
          <section class="footprint-panel" id="footprints" aria-labelledby="footprint-title"><header class="footprint-heading"><h2 id="footprint-title">我的足迹</h2>
            <div class="map-toolbar" hidden><label><input type="checkbox" id="show-route" checked> 显示连线</label><button type="button" id="fit-footprints" title="缩放至当前筛选的足迹">定位足迹 ↗</button></div></header>
            <div id="footprint-map" aria-label="个人足迹交互地图"></div><p id="map-status" class="map-status" role="status">开启 JavaScript 可查看地图。</p>
          </section>
          <div class="gallery-topline"><p>图文笔记</p><p class="gallery-totals">{len(self.journals):02d} 篇笔记 <span>·</span> {photos:02d} 张图片 <span>·</span> {countries:02d} 个国家 / 地区</p></div>
          <div class="gallery-filters" hidden><div class="gallery-tabs" role="group" aria-label="按国家筛选"><button type="button" data-scope="all" aria-pressed="true">全部</button>{country_tabs}</div>
            <div class="gallery-search"><label for="gallery-year">年份</label><select id="gallery-year"><option value="">全部年份</option>{options}</select><label class="visually-hidden" for="gallery-search">搜索笔记、地点或国家</label><input id="gallery-search" type="search" placeholder="搜索笔记、地点…" autocomplete="off"></div></div>
          <section class="gallery-layout" aria-label="图文笔记"><p class="gallery-result" id="gallery-result" role="status">{len(self.journals)} 篇笔记 · 按最新时间排列</p><div class="journal-grid">{''.join(self.card(j) for j in self.journals)}</div><div class="gallery-empty" {'hidden' if self.journals else ''}><p>暂无符合条件的笔记。</p><button type="button" id="gallery-reset" hidden>清除筛选</button></div></section>
          <dialog class="journal-dialog" aria-label="阅读图文笔记"><button type="button" class="dialog-close" aria-label="关闭笔记" autofocus>×</button><div class="dialog-content"></div></dialog>
          <script type="application/json" id="gallery-data">{payload}</script>'''


def build_gallery(base, render, site_name="Flowers for Tuesday"):
    library = GalleryLibrary(base)
    library.discover()
    # Parse and validate the entire collection before writing any pages.
    for journal in library.journals:
        render("gallery", MARKER + '<nav class="gallery-breadcrumb" aria-label="面包屑"><a href="../index.html">← 返回 Gallery</a></nav>' + library.entry(journal),
               journal.note.summary, journal.note.title + " | " + site_name,
               output=journal.note.output.relative_to(library.base).as_posix(),
               extra_head=HEAD + '<link rel="stylesheet" href="{root}/assets/css/notes.css"><link rel="stylesheet" href="{root}/assets/vendor/katex/katex.min.css">')
    render("gallery", library.directory(), "旅行碎片：图文笔记与个人足迹地图。", "Gallery | " + site_name, extra_head=HEAD + MAP_HEAD)
    expected = {j.note.output for j in library.journals}
    for old in library.root.glob("*/index.html"):
        if old not in expected and MARKER in old.read_text(encoding="utf-8"):
            old.unlink()
