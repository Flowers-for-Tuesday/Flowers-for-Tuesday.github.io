"""Build screen palettes from the repository's assets/color/color-palettes.json."""
import json
import re
from html import escape


def rgb(color):
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def mix(first, second, amount):
    """Blend toward second in sRGB, returning a six-digit CSS color."""
    return '#' + ''.join(f'{round(a * (1 - amount) + b * amount):02x}'
                         for a, b in zip(rgb(first), rgb(second)))


def luminance(color):
    channels = [v / 255 for v in rgb(color)]
    return sum((v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4) * w
               for v, w in zip(channels, (.2126, .7152, .0722)))


def contrast(first, second):
    a, b = sorted((luminance(first), luminance(second)))
    return (b + .05) / (a + .05)


def readable(color, backgrounds, dark, ratio=4.5):
    target = '#ffffff' if dark else '#101417'
    for step in range(101):
        candidate = mix(color, target, step / 100)
        if all(contrast(candidate, bg) >= ratio for bg in backgrounds):
            return candidate
    raise ValueError(f'Cannot make {color} readable against {backgrounds}')


def theme_tokens(palette, dark=False):
    colors = [c['hex'] for c in palette['colors']]
    lightest, darkest = max(colors, key=luminance), min(colors, key=luminance)
    seed = colors[palette['accent_index']]
    paper = mix(darkest, '#101417', .68) if dark else mix(lightest, '#ffffff', .72)
    ink = mix(lightest, '#ffffff', .72) if dark else mix(darkest, '#101417', .68)
    surface = mix(paper, '#ffffff', .035 if dark else .45)
    active = mix(paper, seed, .20 if dark else .13)
    hover = mix(paper, seed, .13 if dark else .08)
    code = mix(paper, seed, .12)
    backgrounds = [paper, surface, active, hover, code]
    accent = readable(seed, backgrounds, dark)
    return {
        'paper': paper, 'ink': ink,
        'muted': readable(mix(ink, paper, .33), backgrounds, dark),
        'accent': accent,
        # Neutral separators avoid brown rules in warm palettes.
        'line': '#45494b' if dark else '#d8dcdb',
        'surface': surface, 'surface-active': active, 'surface-hover': hover,
        'field-line': readable(mix(ink, paper, .5), [paper, surface], dark, 3),
        'cover-surface': active, 'quote-surface': hover,
        'quote-ink': readable(ink, [hover], dark), 'quote-line': accent,
        'code-surface': code, 'button-hover': hover,
        'ornament': accent,
    }


def load_palettes(base):
    data = json.loads((base / 'assets/color/color-palettes.json').read_text(encoding='utf-8-sig'))
    if not isinstance(data, list) or not data:
        raise ValueError('Palette source must be a non-empty array')
    palettes = []
    seen = set()
    for entry in data:
        number = entry.get('id')
        if type(number) is not int or number < 1 or number in seen:
            raise ValueError('Invalid or duplicate palette number')
        seen.add(number)
        if not isinstance(entry.get('title'), str) or not entry['title'].strip():
            raise ValueError('Each palette needs a title')
        values = entry.get('colors')
        if not isinstance(values, list) or len(values) != 4:
            raise ValueError('Each palette needs four named colors')
        colors = []
        for value in values:
            if not isinstance(value, dict) or not isinstance(value.get('hex'), str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value['hex']):
                raise ValueError('Invalid HEX color')
            if not isinstance(value.get('name'), str) or not value['name'].strip():
                raise ValueError('Each color needs an English name')
            colors.append({'name': value['name'], 'hex': value['hex'].upper(), 'rgb': list(rgb(value['hex']))})
        image = entry.get('image')
        if not isinstance(image, str) or not re.fullmatch(r'samples/[a-zA-Z0-9_-]+\.png', image):
            raise ValueError('Palette image must reference a PNG inside assets/color/samples')
        if not (base / 'assets/color' / image).is_file():
            raise ValueError(f'Missing palette sample: {image}')
        accent = max(range(len(colors)), key=lambda i: max(colors[i]['rgb']) - min(colors[i]['rgb']))
        palettes.append({
            'id': f'palette-{number:04d}', 'number': number, 'title': entry['title'],
            'accent_index': accent, 'colors': colors, 'image': image,
        })
    return palettes


def build_palettes(base):
    palettes = load_palettes(base)
    default = palettes[0]['id']
    catalog = []
    css = ['/* Generated by scripts/palettes.py; edit assets/color/color-palettes.json. */', '@media screen {']
    for index, palette in enumerate(palettes, 1):
        modes = {mode: theme_tokens(palette, mode == 'dark') for mode in ('light', 'dark')}
        catalog.append({'id': palette['id'], 'index': index,
                        'number': palette['number'], 'title': palette['title'],
                        'colors': [c['hex'] for c in palette['colors']],
                        'color_names': [c['name'] for c in palette['colors']], 'image': palette['image'],
                        'paper': {mode: tokens['paper'] for mode, tokens in modes.items()}})
        for mode, tokens in modes.items():
            if palette['id'] == default:
                fallback = ':root:not([data-palette])' if mode == 'light' else ':root:not([data-palette])[data-theme="dark"]'
                css.append(f'  {fallback},')
            css.append(f'  :root[data-palette="{palette["id"]}"][data-theme="{mode}"] {{')
            css.extend(f'    --{key}: {value};' for key, value in tokens.items())
            css.append('  }')
    css.append('}')
    default_tokens = theme_tokens(next(p for p in palettes if p['id'] == default), True)
    css.extend(['@media screen and (prefers-color-scheme: dark) {', '  :root:not([data-palette]):not([data-theme]) {'])
    css.extend(f'    --{key}: {value};' for key, value in default_tokens.items())
    css.extend(['  }', '}'])
    (base / 'assets/css/palettes.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
    manifest = json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))
    (base / 'assets/js/palettes.js').write_text(
        '// Generated by scripts/palettes.py; edit assets/color/color-palettes.json.\n'
        + f'window.SITE_DEFAULT_PALETTE = {json.dumps(default)};\n'
        + f'window.SITE_PALETTES = {manifest};\n', encoding='utf-8')
    return catalog


def render_color_settings(base):
    palettes = load_palettes(base)
    cards = []
    for palette in palettes:
        title = escape(palette['title'])
        swatches = ''.join(
            f'<span class="color-swatch"><span class="color-chip" style="background-color:{color["hex"]}"></span>'
            f'<span class="color-hex">{color["hex"]}</span></span>'
            for color in palette['colors'])
        cards.append(f'''<li><button class="color-card" type="button" data-select-palette="{palette['id']}"
          aria-pressed="false" aria-label="使用配色 {palette['number']:04d} {title}" disabled>
          <span class="color-card-heading"><span class="color-number">{palette['number']:04d}</span>
          <span class="color-title" lang="ja">{title}</span><span class="color-selected" aria-hidden="true">使用中</span></span>
          <span class="color-swatches">{swatches}</span>
        </button></li>''')
    return f'''<section class="color-current" aria-labelledby="color-current-heading" data-palette-assets="../../assets/color/" hidden>
        <figure class="color-current-sample"><img class="color-current-image" alt="" decoding="async"></figure>
        <div class="color-current-details">
          <h2 id="color-current-heading">当前配色</h2>
          <p class="color-current-name" role="status" aria-live="polite" aria-atomic="true"></p>
          <div class="color-current-swatches color-swatches"></div>
        </div>
      </section>
      <noscript><p>启用 JavaScript 后可以切换配色并查看当前方案。</p></noscript>
      <section aria-label="全部配色方案"><ul class="color-grid" role="list">{''.join(cards)}</ul></section>'''
